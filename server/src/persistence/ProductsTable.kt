package com.restpartijen.api.persistence

import com.restpartijen.api.shared.ProductCategory
import com.restpartijen.api.shared.ProductStatus
import org.jetbrains.exposed.v1.core.Table
import org.jetbrains.exposed.v1.datetime.timestamp

/**
 * Table definition for surplus products (ERD §9.1, table SURPLUS_PRODUCTS).
 *
 * The three product kinds share this one table; [category] tells them apart (§9.3).
 * Allergens live in their own table, because a product has zero to fourteen of them.
 *
 * Owner: Eva (F1). Lives in persistence because other features refer to it (issue #36).
 */
object ProductsTable : Table("surplus_products") {
    /** Generated by the database on insert; never set by the application. */
    val id = long("id").autoIncrement()

    /** The supplier offering this product; the database refuses an unknown supplier (issue #36). */
    val supplierId = long("supplier_id").references(SuppliersTable.id)

    /** Single table inheritance: this column decides which subclass of SurplusProduct a row becomes (§9.3). */
    val category = enumerationByName<ProductCategory>("category", length = 20)

    /** Product name as shown to collectors. */
    val name = varchar("name", length = 255)

    /** Optional: not every product has a barcode (§9.8). */
    val barcode = varchar("barcode", length = 255).nullable()

    /** Price before discount, in whole cents (ADR-07). */
    val originalPriceCents = long("original_price_cents")

    /** The best-before moment; the discount tier and the expiry check count down to it. */
    val bestBeforeAt = timestamp("best_before_at")

    /** Number of units in this product; the model requires at least 1. */
    val quantity = integer("quantity")

    /**
     * Lifecycle status (§9.5). Deleting sets REMOVED instead of removing the row (B-19),
     * so a reservation can keep pointing at the product.
     */
    val status = enumerationByName<ProductStatus>("status", length = 20).default(ProductStatus.LISTED)

    /** Start of the pickup window (§9.9), which is stored as two columns. */
    val pickupFrom = timestamp("pickup_from")

    /** End of the pickup window (§9.9). */
    val pickupUntil = timestamp("pickup_until")

    /** The moment the product was placed. */
    val createdAt = timestamp("created_at")

    // Tells Exposed (and the generated SQL) which column is the primary key.
    override val primaryKey = PrimaryKey(id)
}
